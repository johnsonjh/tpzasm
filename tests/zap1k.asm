;
NEXT:	RET		;ADDITIONAL COMMANDS
			;MAY BE TESTED FROM HERE,
			;AND THE MONITOR EXTENDED
			;FROM BEYOND THIS POINT.
;
;
	Z:
			;END OF PROGRAM
