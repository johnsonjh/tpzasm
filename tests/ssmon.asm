CI:	CALL	IOCHK
	ANI	# CMSK
	JRNZ	CI1
;
; TELEPRINTER ROUTINE
;
TTYIN: CALL	PORA
	JRNZ	..TT1
..TT0:	IN	TTS
	RAR
	JRNC	..TT0
	IN	TTI
	RET
..TT1:	PUSH	B
..TT2:	IN	TTOP
	RAL
	JRC	..TT2
	MVI	A,1
	CALL	RDEL+2
	MVI	B,8
..TT3:	CALL	RDEL
	IN	TTOP
	RAL
	RARR	C
	DJNZ	..TT3
	CALL	RDEL
	MOV	A,C
	POP	B
	RET 
