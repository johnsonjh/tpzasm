RIX:	CALL	RIFF
	JMPR	KPTY

; THIS IS THE INTERNAL KEYBOARD
; HANDLING ROUTINE. IT WILL IGNORE
; RUBOUTS (0FFH) AND BLANKS (00),
; AND IT WILL NOT ECHO CR'S & N'S.
; (NO N'S FOR THE "NULL" COMMAND).
; IT CONVERTS LOWER CASE TO UPPER
; CASE FOR THE LOOK-UP OF COMMANDS.
;
; OTHER CHARACTERS ARE ECHOED AS THEY
; ARE RECIEVED.
;
KI:	CALL	CI	;GET CHARACTER FROM CONSOLE
KPTY: ANI	7FH	;CLEAR PARITY BIT
	RET

PORA:	PUSH	B	;ROUTINE TO FIND ACIA OR PIA
	IN	TTOP
	MOV	B,A
	IN	TTS
	CMP	B
	POP	B
	RET

RDEL:	MVI	A,5	;RESET TIMER FUL BIT INIT
	OUT	TTS
	DCR	A
	OUT	TTS
..RD0:	IN	TTS
	RAL
	JRNC	..RD0
	RET

;
; THIS IS A HEXADECIMAL SEARCH ROUTINE. IT
; TAKES NO ADDRESS PARAMETERS. AS MANY
; BYTES MAY BE ENTERED, SEPARATED BY A COMMA,
; AS DESIRED.  THE MAXIMUM IS 255, BUT 3-4 IS
; TYPICAL, AND MORE THAN 12 WOULD BE UNUSUAL.
; THE ENTIRE MEMORY IS SEARCHED, STARTING
; FROM ZERO, AND ALL STARTING ADDRESSES OF EACH
; OCCURENCE OF THE REQUESTED STRING ARE PRINTED
; ON THE CONSOLE DEVICE.
;
WHERE:	LXI	H,0	;COUNT SEARCH BYTES
	MOV	C,L
	DAD	SP
	DCX	H
	XCHG
..Y0:	CALL	EXPR	;GET ONE BYTE
	POP	H	;PICK IT UP
	MOV	H,L	;STICK IN HIGH BYTE
	PUSH	H	;PUT IT IN STACK
	INX	SP	;ADJUST STACK
	INR	C	;COUNT UP 
	JRNC	..Y0	;MORE TO GO 
	MOV	A,C
	PUSH	PSW
	PUSH	D
	LXI	B,0
	PUSH	B
..Y2: POP	H
	POP	D
	LDAX	D
	CCIR
	JPO	..DONE
	POP	PSW
	PUSH	PSW
	PUSH	D
	PUSH	H
..Y3: DCR	A
	JRZ	..Y5
..Y4: EXAF
	DCX	D
	LDAX	D
	CMP	M
	JRNZ	..Y2
	INX	H
	EXAF
	JMPR	..Y3
..Y5: POP	H
	PUSH	H
	DCX	H
	PUSH	B
	CALL	LFADR
	POP	B
	JMPR	..Y2
..DONE: XCHG
	INX	H
	SPHL
	RET

